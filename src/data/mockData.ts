export function findProductById(id: string): Product | null {
  const match = MOCK_PRODUCTS.find((p) => p.id === id);
  if (match) return match;

  // If user opened a newly registered or simulated product ID
  if (id.startsWith("prod-") || id.startsWith("p")) {
    return {
      id,
      sku: `SKU-${id.toUpperCase().slice(-6)}`,
      name: `Catalog Asset ${id}`,
      category: "Storage",
      unitPrice: 120,
      currentStock: 15,
      minSafetyStock: 20,
      warehouseBin: "Zone-B1",
      supplierId: "sup-1",
      supplierName: "Silicon Logistics",
      createdAt: new Date().toISOString().split("T")[0],
    };
  }

  return null;
}

