import { GoogleGenerativeAI } from '@google/generative-ai';
import { RestockAnalysisInput, RestockRecommendation } from './aiTypes';

function extractJson(text: string): Record<string, unknown> | null {
  try {
    const cleaned = text
      .replace(/```json\s*/gi, '')
      .replace(/```\s*/gi, '')
      .trim();
    return JSON.parse(cleaned);
  } catch {
    const match = text.match(/\{[\s\S]*\}/);
    if (match) {
      try {
        return JSON.parse(match[0]);
      } catch {
        return null;
      }
    }
    return null;
  }
}

export function generateSmartFallbackRecommendation(
  input: RestockAnalysisInput
): RestockRecommendation {
  const chosenSupplier =
    input.currentSupplier ||
    input.availableSuppliers[0] || {
      id: 'unassigned-vendor',
      name: 'Global Cloud Hardware',
      email: 'vendor@globalcloud.com',
      creditLimit: 50000,
    };

  const deficit = Math.max(0, input.minSafetyStock - input.currentStock);
  const bufferUnits = Math.ceil(input.minSafetyStock * 1.5);
  const recommendedQty = Math.max(10, Math.ceil((deficit + bufferUnits) / 5) * 5);
  const estimatedCost = Math.round(recommendedQty * input.unitPrice * 100) / 100;

  const reasoning = `Current stock for ${input.productName} (${input.sku}) is depleted to ${input.currentStock} units against safety threshold of ${input.minSafetyStock}. Critical deficit of ${deficit} units detected. Recommended replenishment of ${recommendedQty} units from verified active supplier ${chosenSupplier.name} to restore a 45-day inventory buffer under warehouse bin ${input.warehouseBin}.`;

  return {
    recommendedSupplierId: chosenSupplier.id,
    recommendedSupplierName: chosenSupplier.name,
    recommendedQuantity: recommendedQty,
    estimatedCost,
    confidenceScore: 94,
    reasoning,
    isFallback: true,
  };
}

export async function analyzeRestockRecommendation(
  input: RestockAnalysisInput
): Promise<RestockRecommendation> {
  const apiKey = process.env.GEMINI_API_KEY;

  if (!apiKey || apiKey.trim() === '') {
    return generateSmartFallbackRecommendation(input);
  }

  try {
    const genAI = new GoogleGenerativeAI(apiKey);
    const model = genAI.getGenerativeModel({ model: 'gemini-2.5-flash' });

    const prompt = `You are the Autonomous Supply Chain Intelligence Engine for NexusWMS.
Analyze the following depleted inventory item and formulate an optimal restock recommendation.

PRODUCT INVENTORY STATE:
- Product Name: ${input.productName}
- SKU: ${input.sku}
- Category: ${input.category}
- Current In-Stock: ${input.currentStock} units
- Minimum Safety Threshold: ${input.minSafetyStock} units
- Unit Price: $${input.unitPrice}
- Warehouse Bin: ${input.warehouseBin}

ELIGIBLE ACTIVE SUPPLIERS:
${JSON.stringify(input.availableSuppliers, null, 2)}

INSTRUCTIONS:
1. You MUST select an eligible ACTIVE supplier from the provided list. Never propose unverified or suspended vendors.
2. Calculate recommended restock quantity to restore at least 2.5x safety stock buffer.
3. Calculate estimated cost = quantity * unitPrice.
4. Provide a confidence score between 70 and 99.
5. Provide a professional, concise reasoning trace explaining the reorder batch size and vendor choice.
6. RESPOND ONLY WITH RAW JSON MATCHING THIS EXACT SCHEMA:
{
  "recommendedSupplierId": "string",
  "recommendedSupplierName": "string",
  "recommendedQuantity": number,
  "estimatedCost": number,
  "confidenceScore": number,
  "reasoning": "string"
}`;

    const result = await model.generateContent(prompt);
    const responseText = result.response.text();
    const parsed = extractJson(responseText);

    if (
      parsed &&
      typeof parsed.recommendedSupplierId === 'string' &&
      typeof parsed.recommendedQuantity === 'number'
    ) {
      return {
        recommendedSupplierId: parsed.recommendedSupplierId,
        recommendedSupplierName: String(parsed.recommendedSupplierName || 'Verified Supplier'),
        recommendedQuantity: Math.max(1, Math.round(parsed.recommendedQuantity)),
        estimatedCost: Number(parsed.estimatedCost) || Math.round(parsed.recommendedQuantity * input.unitPrice * 100) / 100,
        confidenceScore: Math.min(100, Math.max(50, Number(parsed.confidenceScore) || 90)),
        reasoning: String(parsed.reasoning || 'Autonomous restock analysis generated by Gemini 1.5 Flash.'),
        isFallback: false,
      };
    }

    return generateSmartFallbackRecommendation(input);
  } catch {
    return generateSmartFallbackRecommendation(input);
  }
}
